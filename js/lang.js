function autoDetectLanguage() {
    let saved = localStorage.getItem('site_lang') || getCookie('site_lang');
    if (saved === 'hu' || saved === 'en') {
        setLanguage(saved);
        return;
    }

    let navLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
    if (navLang.startsWith('hu')) {
        setLanguage('hu');
    } else {
        setLanguage('en');
    }
}

function acceptCookies() {
    localStorage.setItem('cookie_consent', 'accepted');
    setCookie('cookie_consent', 'accepted', 365);
    document.getElementById('cookieBanner').classList.remove('show');
}

function checkCookieConsent() {
    if (!localStorage.getItem('cookie_consent') && !getCookie('cookie_consent')) {
        setTimeout(() => {
            const banner = document.getElementById('cookieBanner');
            if (banner) banner.classList.add('show');
        }, 800);
    }
}

document.addEventListener('DOMContentLoaded', () => {
    localStorage.removeItem('retro_mode');
    setCookie('retro_mode', '', -1);
    document.body.classList.remove('retro-mode');
    autoDetectLanguage();
    checkCookieConsent();
});
